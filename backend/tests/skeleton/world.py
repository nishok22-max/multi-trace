"""Test worlds for the walking skeleton.

`synthetic_world` builds a small deterministic telemetry set (generated by a seeded RNG in the
test, never read by engine code) plus the real authored PDF; `real_world` seeds from the
downloaded dataset when present. Both register the same case and source layout the seeder uses,
so the engine under test is identical.
"""

from __future__ import annotations

import io
from dataclasses import dataclass
from datetime import date, timedelta
from pathlib import Path

import numpy as np
import pyarrow as pa
import pyarrow.parquet as pq

from tools.gen_seed_pdfs import REPORT, SEED, report_bytes
from trace_adapters.blob_fs import FsBlobStore
from trace_adapters.config_loader import load_config_bundle
from trace_adapters.fakes.cache import DictExtractionCache
from trace_adapters.fakes.clock import FixedClock
from trace_adapters.fakes.llm import FakeLlm, IdentityRedactor
from trace_adapters.fakes.ocr import FakeOcr
from trace_adapters.pdfium_reader import PdfiumReader
from trace_adapters.sqlite.store import SqliteClaimStore
from trace_adapters.telemetry_parquet import ParquetTelemetryReader, series_filename
from trace_core.models.case import Case, CaseVersion, Manifest
from trace_core.models.records import Source
from trace_core.normalise.time import hours_in, local_day_bounds
from trace_core.ports import EnginePorts
from trace_worker.env import snapshot_hashes

TZ = "Asia/Kolkata"
CASE_ID = "case-m21-2015-08-05"
CASE_DAY = date(2015, 8, 5)
ENTITY = "machine:21"
SERIES = "telemetry/machine:21"
CHANNELS = ("volt", "rotate", "pressure", "vibration")
CENTRE = {"volt": 170.0, "rotate": 450.0, "pressure": 100.0, "vibration": 40.0}
SPREAD = {"volt": 15.0, "rotate": 50.0, "pressure": 10.0, "vibration": 5.0}
SPIKE_SPREADS = 15.0  # an excursion of this many spreads on vibration
NOW = "2015-08-06T04:00:00Z"
DATASET = SEED / "dataset"
REAL_DATASET_PRESENT = all(
    (DATASET / f).is_file()
    for f in ("PdM_telemetry.csv", "PdM_errors.csv", "PdM_maint.csv", "PdM_failures.csv")
)


@dataclass(frozen=True)
class World:
    data_dir: Path
    case_id: str
    store: SqliteClaimStore

    def ports(self) -> EnginePorts:
        return EnginePorts(
            blobs=FsBlobStore(self.data_dir / "blobs"),
            pdf=PdfiumReader(),
            ocr=FakeOcr(),
            telemetry=ParquetTelemetryReader(self.data_dir / "derived"),
            cache=DictExtractionCache(),
            clock=FixedClock(NOW),
            llm=FakeLlm(),
            redactor=IdentityRedactor(),
        )

    def manifest(self) -> Manifest:
        manifest = self.store.load_manifest(self.case_id)
        assert manifest is not None
        return manifest


def _hours(day: date) -> list[str]:
    return hours_in(*local_day_bounds(day, TZ))


def write_synthetic_parquet(
    path: Path,
    *,
    spike: bool = True,
    drop_hours: tuple[int, ...] = (),
    duplicate_hour: int | None = None,
) -> None:
    rng = np.random.default_rng(20150805)
    rows: dict[str, list[object]] = {"ts": [], **{c: [] for c in CHANNELS}}
    day = date(2015, 6, 1)
    while day <= date(2015, 10, 1):
        for h, ts in enumerate(_hours(day)):
            if day == CASE_DAY and h in drop_hours:
                continue
            values = {c: CENTRE[c] + SPREAD[c] * float(rng.standard_normal()) for c in CHANNELS}
            if spike and day == CASE_DAY and h == 6:
                values["vibration"] = CENTRE["vibration"] + SPIKE_SPREADS * SPREAD["vibration"]
            rows["ts"].append(ts)
            for c in CHANNELS:
                rows[c].append(values[c])
            if duplicate_hour is not None and day == CASE_DAY and h == duplicate_hour:
                rows["ts"].append(ts)  # same timestamp, different reading
                for c in CHANNELS:
                    rows[c].append(values[c] + SPREAD[c])
        day += timedelta(days=1)
    path.parent.mkdir(parents=True, exist_ok=True)
    pq.write_table(pa.table(rows), path)


def synthetic_world(data_dir: Path, **kwargs: object) -> World:
    derived = data_dir / "derived"
    write_synthetic_parquet(derived / series_filename(SERIES), **kwargs)  # type: ignore[arg-type]
    blobs = FsBlobStore(data_dir / "blobs")

    def put(data: bytes) -> tuple[str, int]:
        ref = blobs.put(io.BytesIO(data), max_bytes=10_000_000)
        return ref.sha256, ref.size

    def source(source_id: str, data: bytes, **fields: object) -> Source:
        sha, size = put(data)
        base = {
            "source_id": source_id, "case_id": CASE_ID, "ingested_at": NOW, "sha256": sha,
            "size": size, "synthetic": True,
        }  # fmt: skip
        return Source.model_validate({**base, **fields})

    logs = {
        "errors": b'"datetime","machineID","errorID"\n2015-07-10 07:00:00,21,"error1"\n',
        "maint": b'"datetime","machineID","comp"\n2015-09-01 06:00:00,21,"comp2"\n',
        "failures": b'"datetime","machineID","failure"\n2015-06-15 06:00:00,21,"comp1"\n',
    }
    sources = [
        source(
            "report-0805", REPORT.read_bytes() if REPORT.is_file() else report_bytes(),
            modality="text", mime="application/pdf", origin="test:report",
        ),
        source(
            "labels", (SEED / "labels.yaml").read_bytes(), modality="text",
            mime="application/x-yaml", origin="test:labels",
        ),
        *[
            source(
                f"events-{kind}-machine-21", data, modality="table", mime="text/csv",
                origin=f"test:{kind}",
                coverage_period={"start": "2015-01-01T00:00:00Z", "end": "2016-01-01T00:00:00Z"},
            )
            for kind, data in logs.items()
        ],
    ]  # fmt: skip
    tel = ParquetTelemetryReader(derived)
    sources.append(
        Source.model_validate(
            {
                "source_id": "telemetry-machine-21",
                "case_id": CASE_ID,
                "modality": "sensor",
                "sha256": tel.partition_sha(SERIES),
                "origin": "test:parquet",
                "ingested_at": NOW,
                "synthetic": True,
                "mime": "application/vnd.apache.parquet",
                "size": (derived / series_filename(SERIES)).stat().st_size,
            }
        )  # fmt: skip
    )
    start, end = local_day_bounds(CASE_DAY, TZ)
    case = Case(
        case_id=CASE_ID, title="Machine 21, 5 August 2015", entities=[ENTITY],
        window_start=start, window_end=end, plant_tz=TZ, created_at=NOW,
    )  # fmt: skip
    store = SqliteClaimStore(data_dir / "trace.db")
    store.append(CASE_ID, [case, *sources])
    return World(data_dir, CASE_ID, store)


def real_world(data_dir: Path) -> World:
    from tools.seed_build import seed_skeleton

    case_id = seed_skeleton(data_dir)
    return World(data_dir, case_id, SqliteClaimStore(data_dir / "trace.db"))


def build_version(world: World) -> CaseVersion:
    """Run build_case in-process (no child) with a fixed clock and fixed identity hashes."""
    from trace_core.build import build_case

    config = load_config_bundle()
    return build_case(
        world.manifest(),
        config,
        [],
        world.ports(),
        hashes=snapshot_hashes(config, PdfiumReader.binary_version()),
    )
