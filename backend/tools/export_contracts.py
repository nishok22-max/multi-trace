"""Export the frozen contracts (IMPLEMENTATION_PLAN A.1).

Writes, deterministically:
- schemas/<Model>.json   Pydantic JSON Schema of every public model
- schemas/openapi.json   OpenAPI 3.1 of the contract app (every C.4 route as a 501 stub)
- frontend/src/lib/api/schema.d.ts   generated by `openapi-typescript` (local install)

`check` regenerates into a temporary directory and compares with what is on disk, so it
never dirties the tree. After the contracts-v1 tag, any difference needs a Contract Change
Request (B approves), then `contracts` to regenerate.
"""

from __future__ import annotations

import difflib
import inspect
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

from pydantic import BaseModel

import trace_core.models as models_pkg
from trace_api.contract_app import build_contract_app

REPO = Path(__file__).resolve().parents[2]
SCHEMAS = REPO / "schemas"
FRONTEND = REPO / "frontend"
DTS_REL = Path("src") / "lib" / "api" / "schema.d.ts"


def _dump(obj: Any) -> str:
    return json.dumps(obj, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def public_models() -> dict[str, type[BaseModel]]:
    """Every BaseModel defined in trace_core.models.* (not re-exports from elsewhere)."""
    found: dict[str, type[BaseModel]] = {}
    for name, obj in vars(models_pkg).items():
        if (
            inspect.isclass(obj)
            and issubclass(obj, BaseModel)
            and obj.__module__.startswith("trace_core.models.")
            and not name.startswith("_")
            and name not in {"CoreModel", "WireModel"}
        ):
            found[name] = obj
    return dict(sorted(found.items()))


def render_files() -> dict[str, str]:
    """relative path (under schemas/) -> text."""
    files = {
        f"{name}.json": _dump(model.model_json_schema(by_alias=True))
        for name, model in public_models().items()
    }
    files["openapi.json"] = _dump(build_contract_app().openapi())
    return files


def _generate_dts(openapi: Path, out: Path) -> None:
    npx = shutil.which("npx")
    if npx is None:
        raise SystemExit("npx not found: install Node and run `npm ci --ignore-scripts` first")
    out.parent.mkdir(parents=True, exist_ok=True)
    cmd = [npx, "--no-install", "openapi-typescript", str(openapi), "-o", str(out)]
    done = subprocess.run(cmd, cwd=FRONTEND, capture_output=True, text=True, check=False)  # noqa: S603
    if done.returncode != 0:
        raise SystemExit("openapi-typescript failed:\n" + done.stdout + done.stderr)


def write(schemas_dir: Path, dts_path: Path) -> None:
    schemas_dir.mkdir(parents=True, exist_ok=True)
    for stale in schemas_dir.glob("*.json"):
        stale.unlink()  # a removed model must not leave a stale schema behind
    for rel, text in render_files().items():
        (schemas_dir / rel).write_text(text, encoding="utf-8", newline="\n")
    _generate_dts(schemas_dir / "openapi.json", dts_path)


def contracts() -> int:
    write(SCHEMAS, FRONTEND / DTS_REL)
    print(f"contracts: wrote {len(list(SCHEMAS.glob('*.json')))} schemas and schema.d.ts")
    return 0


def _tree(root: Path, pattern: str) -> dict[str, str]:
    return {p.name: p.read_text(encoding="utf-8") for p in sorted(root.glob(pattern))}


def contracts_check() -> int:
    """Fail if the generated contracts differ from the files on disk."""
    problems: list[str] = []
    with tempfile.TemporaryDirectory() as tmp:
        tmp_dir = Path(tmp)
        write(tmp_dir / "schemas", tmp_dir / "schema.d.ts")
        fresh = _tree(tmp_dir / "schemas", "*.json")
        disk = _tree(SCHEMAS, "*.json") if SCHEMAS.is_dir() else {}
        for name in sorted(fresh.keys() | disk.keys()):
            if name not in disk:
                problems.append(f"missing on disk: schemas/{name}")
            elif name not in fresh:
                problems.append(f"stale on disk: schemas/{name}")
            elif fresh[name] != disk[name]:
                diff = difflib.unified_diff(
                    disk[name].splitlines(),
                    fresh[name].splitlines(),
                    f"disk/{name}",
                    f"generated/{name}",
                    lineterm="",
                    n=1,
                )
                problems.append("\n".join(list(diff)[:30]))
        dts_disk = FRONTEND / DTS_REL
        fresh_dts = (tmp_dir / "schema.d.ts").read_text(encoding="utf-8")
        if not dts_disk.is_file():
            problems.append(f"missing on disk: {DTS_REL.as_posix()}")
        elif dts_disk.read_text(encoding="utf-8") != fresh_dts:
            problems.append(f"differs from generated: {DTS_REL.as_posix()}")
    for p in problems:
        print(p)
    print(
        "contracts-check: FAIL (run `contracts` and file a Contract Change Request)"
        if problems
        else "contracts-check: ok"
    )
    return 1 if problems else 0


def main() -> int:
    return contracts_check() if sys.argv[1:] == ["--check"] else contracts()


if __name__ == "__main__":
    sys.exit(main())
