"""Slides are updated from the engine, never the other way round (h32). This writes
`docs/ENGINE_NUMBERS.md` from the engine's own outputs: the Demo 0 golden (computed by the engine
from seeded data) and the latest evaluation reports. Nothing here is typed.

    python -m tools.slide_numbers
"""

from __future__ import annotations

import json
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

BACKEND = Path(__file__).resolve().parents[1]
REPO = BACKEND.parent
GOLDEN = BACKEND / "tests" / "golden" / "files"
OUT = REPO / "docs" / "ENGINE_NUMBERS.md"


def _load(path: Path) -> dict[str, Any] | None:
    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else None


def demo0_section() -> list[str]:
    golden = _load(GOLDEN / "demo0_headline.json")
    if golden is None:
        return ["## Demo 0", "", "The Demo 0 golden is missing: run `make golden`.", ""]
    env, state = golden["envelope"], golden["state"]
    conflict = golden["conflicts"][0] if golden["conflicts"] else ["n/a", "n/a"]
    return [
        "## Demo 0: the headline disagreement",
        "",
        f"- Outcome: **{golden['outcome']}**; {golden['reason']}",
        f"- T_D (robust max-z of the day): {state['T_D']}",
        f"- T* (conformal threshold, alpha = 0.05): {state['T_star']}",
        f"- Quiet days behind the threshold (n): {env['n']}; pooled: {env['pooled']}",
        f"- Conflict magnitude: observed {conflict[0]} against threshold {conflict[1]}",
        "",
    ]


def eval_section(title: str, path: Path) -> list[str]:
    report = _load(path)
    if report is None:
        return [f"## {title}", "", f"Not run yet ({path.name}).", ""]
    far = report["quiet_day_false_alarm"]
    lines = [
        f"## {title} (split: {report['split']}, run {report['run_id']})",
        "",
        f"- Conflict detection, overall: precision {report['overall']['precision']:.3f}, "
        f"recall {report['overall']['recall']:.3f}, F1 {report['overall']['f1']:.3f} "
        f"(n = {report['overall']['n']})",
        f"- Quiet-day false alarms: {far['point']:.3%} (95% CI {far['lower']:.3%} to {far['upper']:.3%}, n = {far['n']})",
        f"- Gaps read as normal: {report['gaps_read_as_normal']}; averaged outputs: {report['averaged_outputs']}",
        f"- Entity linking: accuracy@1 {report['entity_accuracy_at1']:.3f}, @3 {report['entity_accuracy_at3']:.3f}",
        f"- ECE {report['ece_before']:.3f} and Brier {report['brier_before']:.3f} before calibration "
        "(uncalibrated: no fit exists)",
    ]
    for b in report["baselines"]:
        lines.append(
            f"- Baseline {b['name']}: {b['answer_text']} "
            f"({'surfaced' if b['surfaced_conflict'] else 'did not surface'} the conflict)"
        )
    return [*lines, ""]


def main() -> int:
    data = REPO / "data"
    body = [
        "# Engine numbers for the slides",
        "",
        f"Generated by `python -m tools.slide_numbers` on {datetime.now(UTC):%Y-%m-%d %H:%M} UTC. "
        "Every number below is read from an engine output; edit the slides to match this file, "
        "never this file to match the slides.",
        "",
        *demo0_section(),
        *eval_section("Dev evaluation", data / "eval_report.json"),
        *eval_section("Holdout evaluation", data / "eval_report_holdout.json"),
    ]
    OUT.write_text("\n".join(body) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
